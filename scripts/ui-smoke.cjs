const { app, BrowserWindow, ipcMain } = require('electron');
const path = require('node:path');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
const os = require('node:os');
const { encode } = require('../src/encoder.cjs');
app.whenReady().then(async()=>{
  let testDir;
  try {
    let fixture=false,sourceRequests=0;
    ipcMain.handle('sources',()=>{sourceRequests++;return fixture?[{id:'test:screen',name:'测试屏幕',thumbnail:''}]:[];});
    let cancelRegion=false;
    ipcMain.handle('region',()=>cancelRegion?null:({x:.25,y:.25,width:.5,height:.5}));
    ipcMain.handle('permissions',()=>({platform:process.platform,shortcut:true}));
    const win=new BrowserWindow({width:1120,height:820,show:false,frame:false,transparent:true,backgroundColor:'#00000000',webPreferences:{preload:path.resolve(__dirname,'../src/preload.cjs'),contextIsolation:true,nodeIntegration:false,sandbox:true,backgroundThrottling:false}});
    ipcMain.handle('surface',(_,next)=>win.setSize(next==='toolbar'?680:next==='result'?900:1120,next==='toolbar'?88:next==='result'?680:820));
    let cancelSource=false;
    ipcMain.handle('pick-source',()=>fixture&&!cancelSource?'test:screen':null);
    let optionsOpened=false;
    ipcMain.handle('options',()=>{optionsOpened=true;win.webContents.send('toolbar-command',{type:'preset',preset:'clear'});win.webContents.send('toolbar-command',{type:'target',checked:true});});
    const errors=[];
    win.webContents.on('console-message',(_e,level,message)=>{if(level>=3)errors.push(message);});
    await win.loadFile(path.resolve(__dirname,'../src/index.html'));
    await new Promise(r=>setTimeout(r,800));
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("record").disabled'),true);
    const initialRequests=sourceRequests;
    for(const name of ['files','settings','capture']) {
      await win.webContents.executeJavaScript(`document.getElementById('tab-${name}').click()`);
      assert.equal(await win.webContents.executeJavaScript(`document.getElementById('panel-${name}').hidden`),false);
      assert.equal(await win.webContents.executeJavaScript('document.querySelectorAll("[role=tabpanel]:not([hidden])").length'),1);
      assert.equal(await win.webContents.executeJavaScript('document.querySelectorAll("[role=tab][aria-selected=true]").length'),1);
    }
    assert.equal(sourceRequests,initialRequests,'Tab changes must not refresh capture sources');
    await win.webContents.executeJavaScript('document.getElementById("tab-capture").dispatchEvent(new KeyboardEvent("keydown",{key:"ArrowLeft",bubbles:true}))');
    assert.equal(await win.webContents.executeJavaScript('document.activeElement.id'),'tab-settings');
    await win.webContents.executeJavaScript('document.querySelector("[data-preset=clear]").click();document.querySelector("[data-mode=region]").click()');
    await new Promise(r=>setTimeout(r,100));
    assert.equal(await win.webContents.executeJavaScript('document.querySelector("[data-preset=clear]").classList.contains("selected")'),true);
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("choose-region").hidden'),false);
    await win.webContents.executeJavaScript('document.querySelector("[data-preset=balanced]").click();document.querySelector("[data-mode=screen]").click();document.getElementById("message").hidden=true');
    await new Promise(r=>setTimeout(r,100));
    await win.webContents.executeJavaScript('document.getElementById("message").hidden=true;document.getElementById("tab-capture").click()');
    win.showInactive();
    await new Promise(r=>setTimeout(r,350));
    const overflow=await win.webContents.executeJavaScript('document.documentElement.scrollWidth > innerWidth');
    assert.equal(overflow,false);
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("record").getBoundingClientRect().bottom <= innerHeight'),true);
    await fs.mkdir(path.resolve(__dirname,'../test-output'),{recursive:true});
    const image=await win.webContents.capturePage();
    await fs.writeFile(path.resolve(__dirname,'../test-output/interface.png'),image.toPNG());
    for(const name of ['files','settings']) {
      await win.webContents.executeJavaScript(`document.getElementById('tab-${name}').click()`);
      await new Promise(r=>setTimeout(r,150));
      await fs.writeFile(path.resolve(__dirname,`../test-output/${name}.png`),(await win.webContents.capturePage()).toPNG());
    }
    await win.webContents.executeJavaScript('document.getElementById("tab-capture").click()');
    win.setSize(960,740);
    await new Promise(r=>setTimeout(r,200));
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("record").getBoundingClientRect().bottom <= innerHeight'),true);
    assert.equal(await win.webContents.executeJavaScript('document.querySelector(".bottom-nav").getBoundingClientRect().bottom <= innerHeight'),true);
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("record").getBoundingClientRect().bottom <= document.querySelector(".bottom-nav").getBoundingClientRect().top'),true);
    win.setSize(1120,820);
    fixture=true;
    testDir=await fs.mkdtemp(path.join(os.tmpdir(),'luma-ui-test-'));
    const input=path.join(testDir,'recording.webm'),output=path.join(testDir,'recording.gif');
    let settings,saveCalls=0,captureCalls=0;
    ipcMain.handle('select',()=>{});
    ipcMain.handle('begin',async(_,options)=>{settings=options;await fs.writeFile(input,Buffer.alloc(0));});
    ipcMain.handle('chunk',async(_,chunk)=>{assert.ok(chunk instanceof Uint8Array);await fs.appendFile(input,chunk);});
    ipcMain.handle('abort',()=>{});
    ipcMain.handle('finish',async()=>{
      captureCalls++;
      const result=await encode({binary:require('ffmpeg-static'),input,output,options:settings,onProgress:p=>win.webContents.send('progress',p)});
      return {...result,url:require('node:url').pathToFileURL(output).href};
    });
    const savedFile=path.join(testDir,'saved.gif');
    ipcMain.handle('save',async(_,kind)=>{
      assert.equal(kind,'gif');saveCalls++;
      if(saveCalls===1||saveCalls===4)return null;
      if(saveCalls===2||saveCalls===5)throw new Error('测试保存失败');
      await fs.copyFile(output,savedFile);return savedFile;
    });
    await win.webContents.executeJavaScript(`
      navigator.mediaDevices.getDisplayMedia=async()=>{
        const canvas=document.createElement('canvas');canvas.width=640;canvas.height=360;
        const ctx=canvas.getContext('2d');let tick=0;
        const drawing=setInterval(()=>{ctx.fillStyle='#d9e3fb';ctx.fillRect(0,0,640,360);ctx.fillStyle='#4262d9';ctx.fillRect((tick++*5)%580,140,60,60);ctx.font='28px sans-serif';ctx.fillText('Luma recording test',35,75);},33);
        const stream=canvas.captureStream(30);stream.getVideoTracks()[0].addEventListener('ended',()=>clearInterval(drawing));return stream;
      };
      document.getElementById('refresh').click();
    `);
    await new Promise(r=>setTimeout(r,200));
    await win.webContents.executeJavaScript('document.querySelector("[data-mode=region]").click()');
    await new Promise(r=>setTimeout(r,150));
    await win.webContents.executeJavaScript('document.getElementById("choose-region").click()');
    await new Promise(r=>setTimeout(r,150));
    const selectedRequests=sourceRequests;
    await win.webContents.executeJavaScript('document.getElementById("tab-settings").click();document.querySelector("[data-preset=clear]").click();document.getElementById("target").click();document.getElementById("tab-files").click();document.getElementById("tab-capture").click()');
    assert.equal(sourceRequests,selectedRequests);
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("target").checked'),true);
    assert.ok(await win.webContents.executeJavaScript('document.getElementById("selection-note").textContent.includes("50%")'));
    assert.ok(await win.webContents.executeJavaScript('document.getElementById("preset-summary").textContent.includes("高清细节")'));
    await win.webContents.executeJavaScript('document.getElementById("compact-button").click()');
    await new Promise(r=>setTimeout(r,150));
    assert.equal(await win.webContents.executeJavaScript('document.body.classList.contains("surface-toolbar")'),true);
    assert.equal(await win.webContents.executeJavaScript('getComputedStyle(document.querySelector("main")).display'),'none');
    assert.equal(await win.webContents.executeJavaScript('getComputedStyle(document.documentElement).backgroundColor'),'rgba(0, 0, 0, 0)');
    await win.webContents.executeJavaScript('document.getElementById("toolbar-options").click()');
    await new Promise(r=>setTimeout(r,150));
    assert.equal(optionsOpened,true);
    cancelSource=true;
    await win.webContents.executeJavaScript('document.querySelector("[data-toolbar-mode=window]").click()');
    await new Promise(r=>setTimeout(r,150));
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("toolbar-record").disabled'),true);
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("sources").selectedIndex'),-1);
    cancelSource=false;
    await win.webContents.executeJavaScript('document.querySelector("[data-toolbar-mode=window]").click()');
    await new Promise(r=>setTimeout(r,150));
    assert.equal(await win.webContents.executeJavaScript('document.querySelector("[data-toolbar-mode=window]").getAttribute("aria-pressed")'),'true');
    cancelRegion=true;
    await win.webContents.executeJavaScript('document.querySelector("[data-toolbar-mode=region]").click()');
    await new Promise(r=>setTimeout(r,150));
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("record").disabled'),true);
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("toolbar-record-label").textContent'),'选择区域');
    assert.equal(captureCalls,0);
    cancelRegion=false;
    await win.webContents.executeJavaScript('document.getElementById("toolbar-record").click()');
    await new Promise(r=>setTimeout(r,150));
    assert.equal(await win.webContents.executeJavaScript('document.querySelector("[data-toolbar-mode=region]").getAttribute("aria-pressed")'),'true');
    assert.ok(await win.webContents.executeJavaScript('document.getElementById("toolbar-caption-detail").textContent.includes("区域已选")'));
    assert.equal(await win.webContents.executeJavaScript('document.documentElement.scrollWidth > innerWidth'),false);
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("capture-toolbar").getBoundingClientRect().bottom <= innerHeight'),true);
    await fs.writeFile(path.resolve(__dirname,'../test-output/floating-toolbar.png'),(await win.webContents.capturePage()).toPNG());
    await win.webContents.executeJavaScript('document.getElementById("toolbar-record").click()');
    const deadline=Date.now()+20000;
    while(!await win.webContents.executeJavaScript('document.getElementById("record").classList.contains("stop")')){if(Date.now()>deadline)throw new Error('Recording did not start');await new Promise(r=>setTimeout(r,100));}
    assert.deepEqual(settings,{mode:'region',preset:'clear',crop:{x:.25,y:.25,width:.5,height:.5},targetMB:8});
    await win.webContents.executeJavaScript('document.getElementById("tab-settings").click()');
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("target").disabled'),true);
    await win.webContents.executeJavaScript('document.getElementById("tab-capture").click()');
    await new Promise(r=>setTimeout(r,1500));
    win.webContents.send('stop-recording');
    while(await win.webContents.executeJavaScript('document.getElementById("result").hidden')){if(Date.now()>deadline)throw new Error('Conversion did not finish');await new Promise(r=>setTimeout(r,100));}
    while(saveCalls<1 || await win.webContents.executeJavaScript('document.getElementById("save").disabled')){if(Date.now()>deadline)throw new Error('Automatic save dialog did not finish');await new Promise(r=>setTimeout(r,100));}
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("save").disabled'),false);
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("panel-files").hidden'),false);
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("tab-files").getAttribute("aria-selected")'),'true');
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("files-empty").hidden'),true);
    assert.equal(await win.webContents.executeJavaScript('document.body.classList.contains("surface-studio")'),true);
    assert.equal(await win.webContents.executeJavaScript('document.body.classList.contains("result-view")'),true);
    assert.equal(await win.webContents.executeJavaScript('getComputedStyle(document.querySelector(".bottom-shell")).display'),'none');
    assert.equal(await win.webContents.executeJavaScript('document.body.dataset.flowStage'),'save');
    assert.ok(await win.webContents.executeJavaScript('document.getElementById("save-status").textContent.includes("尚未保存")'));
    await win.webContents.executeJavaScript('document.getElementById("save").click()');
    await new Promise(r=>setTimeout(r,150));
    assert.ok(await win.webContents.executeJavaScript('document.getElementById("message").textContent.includes("保存失败")'));
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("save").disabled'),false);
    assert.equal(captureCalls,1,'Saving failures must not trigger encoding again');
    await win.webContents.executeJavaScript('document.getElementById("save").click()');
    await new Promise(r=>setTimeout(r,150));
    assert.equal(saveCalls,3);
    assert.equal(await win.webContents.executeJavaScript('document.body.dataset.flowStage'),'done');
    assert.deepEqual(await fs.readFile(savedFile),await fs.readFile(output));
    await fs.writeFile(path.resolve(__dirname,'../test-output/saved-result.png'),(await win.webContents.capturePage()).toPNG());
    await win.webContents.executeJavaScript('document.getElementById("save").click()');
    await new Promise(r=>setTimeout(r,150));
    assert.equal(saveCalls,4);
    assert.equal(await win.webContents.executeJavaScript('document.body.dataset.flowStage'),'done');
    assert.ok(await win.webContents.executeJavaScript('document.getElementById("save-status").textContent.includes("本次另存已取消")'));
    await win.webContents.executeJavaScript('document.getElementById("save").click()');
    await new Promise(r=>setTimeout(r,150));
    assert.equal(saveCalls,5);
    assert.equal(await win.webContents.executeJavaScript('document.body.dataset.flowStage'),'done');
    assert.deepEqual(await fs.readFile(savedFile),await fs.readFile(output));
    cancelRegion=true;
    await win.webContents.executeJavaScript('document.getElementById("flow-new").click()');
    await new Promise(r=>setTimeout(r,200));
    assert.equal(await win.webContents.executeJavaScript('document.getElementById("record").disabled'),true);
    assert.equal(await win.webContents.executeJavaScript('document.body.classList.contains("surface-toolbar")'),true);
    assert.equal(captureCalls,1);
    assert.ok((await fs.stat(output)).size>100);
    assert.deepEqual(errors,[]);
    await fs.rm(testDir,{recursive:true,force:true});
    console.log('Flow passed: region confirmation before recording → one GIF conversion → automatic save dialog → cancel/failure retry → byte-identical local GIF; next recording requires a fresh region.');
    app.exit(0);
  } catch(e) {console.error(e);if(testDir)await fs.rm(testDir,{recursive:true,force:true});app.exit(1);}
});
